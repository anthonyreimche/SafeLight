// Writes embedded.ts from the page's three files. A `?raw` import would do the
// same in the build, but the test runner blanks every stylesheet import, so the
// strings are kept in source. Run after editing index.html, app.js or app.css:
//   node src/cli/live/page/generate.mjs

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const read = (name) => readFileSync(path.join(here, name), "utf-8").replace(/\r\n/g, "\n");
const SOURCES = [["PAGE_HTML", "index.html"], ["APP_JS", "app.js"], ["APP_CSS", "app.css"]];

const header = `${read("generate.mjs").split("\n").slice(0, 4).join("\n")}

// Generated by generate.mjs from index.html, app.js and app.css. Edit those, then run it again.
`;
const body = SOURCES.map(([name, file]) => `\nexport const ${name} = ${JSON.stringify(read(file))};\n`).join("");
writeFileSync(path.join(here, "embedded.ts"), header + body);
